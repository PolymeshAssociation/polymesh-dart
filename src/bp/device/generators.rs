/// The fixed generator points the device uses, compiled into the device build.
#[derive(Copy, Clone)]
pub struct DeviceGenerators {
    pub account_comm_key: [PallasA; NUM_GENERATORS],
    pub comm_re_rand_gen: PallasA,
    pub anchor_gen: PallasA,
    pub leg_asset_value_gen: PallasA,
}

impl DeviceGenerators {
    pub fn new() -> Result<Self, Error> {
        let mut account_comm_key = [PallasA::default(); NUM_GENERATORS];
        for (g, bytes) in account_comm_key.iter_mut().zip(ACCOUNT_COMM_KEY.iter()) {
            *g = decode(bytes)?;
        }
        Ok(Self {
            account_comm_key,
            comm_re_rand_gen: decode(&COMM_RE_RAND_GEN)?,
            anchor_gen: decode(&ANCHOR_GEN)?,
            leg_asset_value_gen: decode(&LEG_ASSET_VALUE_GEN)?,
        })
    }

    pub fn sig_key_gen(&self) -> PallasA {
        self.account_comm_key.sk_gen()
    }

    pub fn enc_key_gen(&self) -> PallasA {
        self.account_comm_key.sk_enc_gen()
    }
}

fn decode(bytes: &[u8; 32]) -> Result<PallasA, Error> {
    Ok(PallasA::deserialize_compressed(&bytes[..])?)
}

#[cfg(all(test, feature = "host_proofs"))]
mod tests {
    use super::*;
    use crate::curve_tree::{AccountTreeConfig, CurveTreeConfig};
    use crate::dart_gens;

    fn compress(p: PallasA) -> [u8; 32] {
        let mut bytes = [0u8; 32];
        ark_serialize::CanonicalSerialize::serialize_compressed(&p, &mut bytes[..]).unwrap();
        bytes
    }

    #[test]
    fn device_generators_match_host() {
        let gens = dart_gens();
        let pc_gens = AccountTreeConfig::parameters().even_parameters.pc_gens();
        let account_comm_key = gens.account_comm_key().as_gens().map(compress);
        let comm_re_rand_gen = compress(pc_gens.B_blinding);
        let anchor_gen = compress(pc_gens.B);
        let leg_asset_value_gen = compress(gens.leg_asset_value_gen());

        assert_eq!(
            (
                ACCOUNT_COMM_KEY,
                COMM_RE_RAND_GEN,
                ANCHOR_GEN,
                LEG_ASSET_VALUE_GEN
            ),
            (
                account_comm_key,
                comm_re_rand_gen,
                anchor_gen,
                leg_asset_value_gen
            ),
            "ACCOUNT_COMM_KEY = {account_comm_key:?}\nCOMM_RE_RAND_GEN = {comm_re_rand_gen:?}\nANCHOR_GEN = {anchor_gen:?}\nLEG_ASSET_VALUE_GEN = {leg_asset_value_gen:?}"
        );

        let device = DeviceGenerators::new().unwrap();
        assert_eq!(device.sig_key_gen(), gens.sig_key_gen());
        assert_eq!(device.enc_key_gen(), gens.enc_key_gen());
    }
}
